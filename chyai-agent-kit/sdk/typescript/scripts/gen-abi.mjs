// Regenerates src/abi/*.ts (typed `as const` ABIs) and python/agentpad/abi/*.json from ../contracts/abi.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../contracts/abi");
const outTs = path.resolve(here, "../src/abi");
const outPy = path.resolve(here, "../python/agentpad/abi");
fs.mkdirSync(outTs, { recursive: true });
fs.mkdirSync(outPy, { recursive: true });
const names = [];
for (const f of fs.readdirSync(src).filter((f) => f.endsWith(".json"))) {
  const name = f.replace(/\.json$/, "");
  const raw = JSON.parse(fs.readFileSync(path.join(src, f), "utf8"));
  const abi = Array.isArray(raw) ? raw : raw.abi;
  fs.writeFileSync(path.join(outTs, `${name}.ts`), `// Generated by scripts/gen-abi.mjs from contracts/abi/${f}. Do not edit.\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`);
  fs.writeFileSync(path.join(outPy, `${name}.json`), JSON.stringify(abi));
  names.push(name);
}
fs.writeFileSync(path.join(outTs, "index.ts"), names.map((n) => `export { ${n}Abi } from "./${n}.js";`).join("\n") + "\n");
console.log("ABIs:", names.join(", "));
