// Copies contract ABIs from ../contracts/abi into a typed TS module (as const) so viem infers types
// and the backend image does not depend on the contracts folder at runtime.
import fs from "node:fs";
import path from "node:path";
const here = path.dirname(new URL(import.meta.url).pathname);
const src = path.resolve(here, "../../contracts/abi");
const names = ["AgentRegistry", "LaunchFactory", "BondingNFT", "AgentToken", "FeeSplitter", "RewardPool", "TraitRandomness"];
let out = "// AUTO-GENERATED by scripts/gen-abi.mjs from contracts/abi/*.json — do not edit.\n";
for (const n of names) {
  const abi = JSON.parse(fs.readFileSync(path.join(src, `${n}.json`), "utf8"));
  out += `export const ${n}Abi = ${JSON.stringify(Array.isArray(abi) ? abi : abi.abi)} as const;\n`;
}
fs.writeFileSync(path.resolve(here, "../src/chain/abi.ts"), out);
console.log("wrote src/chain/abi.ts");
